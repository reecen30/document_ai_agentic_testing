def _render_list(items: List[Any], empty_msg: str = "None.") -> str:
    if not items:
        return f"<p>{empty_msg}</p>"
    lis = "".join(f"<li>{_escape(str(item))}</li>" for item in items)
    return f"<ul>{lis}</ul>"


def _escape(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")


def _render_metrics_rows(metrics: Dict[str, Any]) -> str:
    rows = []
    for key, val in metrics.items():
        if isinstance(val, dict):
            b = _escape(str(val.get("baseline", "")))
            c = _escape(str(val.get("candidate", "")))
            d_raw = val.get("delta")
            try:
                d_f = float(d_raw)
                d_cls = "improvement" if d_f > 0 else "regression" if d_f < 0 else "neutral"
                d_str = f'<span class="{d_cls}">{d_f:+.4f}</span>'
            except (TypeError, ValueError):
                d_str = _escape(str(d_raw or ""))
            rows.append(f"<tr><td>{_escape(key)}</td><td>{b}</td><td>{c}</td><td>{d_str}</td></tr>")
        else:
            rows.append(f"<tr><td>{_escape(key)}</td><td colspan='3'>{_escape(str(val))}</td></tr>")
    return "\n    ".join(rows) if rows else "<tr><td colspan='4'>No metrics available.</td></tr>"


