# WriteHtmlReportTool
# ---------------------------------------------------------------------------

class WriteHtmlReportInput(BaseModel):
    run_state: Dict[str, Any] = Field(
        ...,
        description=(
            "Full run state dict. Expected keys: run_id, workspace_path, verdict "
            "(PASS|WARN|BLOCK), transaction_count, metrics (dict), improvements (list), "
            "regressions (list), hidden_risks (list), root_causes (list), "
            "patch_candidates (list), routing_decision (str)."
        ),
    )


class WriteHtmlReportTool(BaseTool):
    name: str = "write_html_report"
    description: str = (
        "Generate an HTML testing report from the run_state dict and write it to "
        "<workspace_path>/report.html. Includes verdict badge, metrics table, "
        "improvements, regressions, hidden risks, root causes, patch candidates, "
        "and routing decision. Returns JSON with status and path."
    )
    args_schema: Type[BaseModel] = WriteHtmlReportInput

    def _run(self, run_state: Dict[str, Any]) -> str:
        try:
            workspace_path = run_state.get("workspace_path", ".")
            report_path = os.path.join(workspace_path, "report.html")
            os.makedirs(workspace_path, exist_ok=True)

            run_id = run_state.get("run_id", "UNKNOWN")
            verdict = str(run_state.get("verdict", "UNKNOWN")).upper()
            if verdict not in ("PASS", "WARN", "BLOCK"):
                verdict = "UNKNOWN"
            transaction_count = run_state.get("transaction_count", 0)
            generated_at = _ts()

            metrics = run_state.get("metrics") or {}
            improvements = run_state.get("improvements") or []
            regressions = run_state.get("regressions") or []
            hidden_risks = run_state.get("hidden_risks") or []
            root_causes = run_state.get("root_causes") or []
            patch_candidates = run_state.get("patch_candidates") or []
            routing_decision = _escape(str(run_state.get("routing_decision", "No routing decision provided.")))

            html = _HTML_TEMPLATE.format(
                run_id=_escape(run_id),
                verdict=verdict,
                generated_at=generated_at,
                transaction_count=transaction_count,
                metrics_rows=_render_metrics_rows(metrics),
                improvements_html=_render_list(improvements, "No improvements detected."),
                regressions_html=_render_list(regressions, "No regressions detected."),
                hidden_risks_html=_render_list(hidden_risks, "No hidden risks detected."),
                root_causes_html=_render_list(root_causes, "No root causes identified."),
                patch_candidates_html=_render_list(patch_candidates, "No patch candidates."),
                routing_decision=routing_decision,
            )

            with open(report_path, "w", encoding="utf-8") as f:
                f.write(html)

            return json.dumps({"status": "ok", "path": report_path, "verdict": verdict})
        except Exception as e:
            return json.dumps({"error": str(e), "tool": "write_html_report"})


